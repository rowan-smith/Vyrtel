// Regenerates the outlined [V]yrtel artwork from Inter, so no file depends on a font being installed:
//
//   docs/brand/vyrtel-wordmark-{dark,light}.svg        the wordmark
//   docs/brand/vyrtel-lockup-tagline-{dark,light}.svg  wordmark + "View. Trace. Understand."
//   web/src/lib/wordmark.ts                            "yrtel" path data used by the web UI and site
//
// Run from docs/: `npm run brand`. Geometry is the brand pack's Trace V in a 256 box (arms end on
// y = 196, node at (128, 198)); "yrtel" is Inter Bold at 126 units with -5 tracking, its baseline on
// the arm ends and the "y" tucked 0.167em under the iris arm's top cap.

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

import opentype from 'opentype.js';

const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(here, '../..');
const fontFile = (w) => path.resolve(here, `../node_modules/@fontsource/inter/files/inter-latin-${w}-normal.woff`);
const bold = opentype.loadSync(fontFile(700));
const semibold = opentype.loadSync(fontFile(600));

const MIDNIGHT = '#07131F';
const PAPER = '#F6F8FB';
const TAGLINE = 'View. Trace. Understand.';

/** "yrtel" as path data: kerned, with fixed tracking after each glyph (like CSS letter-spacing). */
function word(font, x0, baseline, size, tracking) {
  let x = x0;
  let d = '';
  const glyphs = font.stringToGlyphs('yrtel');
  glyphs.forEach((g, i) => {
    d += g.getPath(x, baseline, size).toPathData(2);
    x += (g.advanceWidth / font.unitsPerEm) * size + tracking;
    if (i < glyphs.length - 1) x += (font.getKerningValue(g, glyphs[i + 1]) / font.unitsPerEm) * size;
  });
  return { d, end: x, bbox: font.getPath('yrtel', x0, baseline, size).getBoundingBox() };
}

// ---------- wordmark + lockup SVGs ----------

const w = word(bold, 198, 196, 126, -5);
const minX = 30;
const minY = 30;
const maxX = Math.ceil(w.end + 10);
const maxY = Math.ceil(Math.max(w.bbox.y2, 218) + 6);

const mark = (ring, node) =>
  `<path d="M48 52 L126 196" fill="none" stroke="#39E6C2" stroke-width="26" stroke-linecap="round"/>` +
  `<path d="M208 52 L130 196" fill="none" stroke="#7C72FF" stroke-width="26" stroke-linecap="round"/>` +
  `<circle cx="128" cy="198" r="18" fill="${ring}"/><circle cx="128" cy="198" r="11" fill="${node}"/>`;

// The node is always Paper ringed in Midnight; only the word (and tagline) colour changes.
const variants = {
  dark: { word: PAPER, tag: '#A8B6C8' },
  light: { word: MIDNIGHT, tag: '#5A6B80' },
};

const tagSize = 34;
const tagY = maxY + 40;
const tagOpts = { letterSpacing: 0.015 };
// Centre the tagline under the wordmark (V's left cap edge to the end of "l").
const tagMeasure = semibold.getPath(TAGLINE, 0, tagY, tagSize, tagOpts).getBoundingBox();
const tagX = (35 + w.bbox.x2) / 2 - (tagMeasure.x1 + tagMeasure.x2) / 2;
const tag = semibold.getPath(TAGLINE, tagX, tagY, tagSize, tagOpts);
const tagBox = tag.getBoundingBox();
const minX2 = Math.min(minX, Math.floor(tagBox.x1 - 10));
const maxX2 = Math.max(maxX, Math.ceil(tagBox.x2 + 10));
const maxY2 = Math.ceil(tagBox.y2 + 10);

const svg = (vb, width, height, label, body) =>
  `<svg xmlns="http://www.w3.org/2000/svg" viewBox="${vb}" width="${width}" height="${height}" role="img" aria-label="${label}">${body}</svg>\n`;

const written = [];
const write = (file, content) => {
  fs.writeFileSync(path.join(root, file), content);
  written.push(file);
};

for (const [name, v] of Object.entries(variants)) {
  write(
    `docs/brand/vyrtel-wordmark-${name}.svg`,
    svg(`${minX} ${minY} ${maxX - minX} ${maxY - minY}`, maxX - minX, maxY - minY, 'Vyrtel', `${mark(MIDNIGHT, PAPER)}<path fill="${v.word}" d="${w.d}"/>`),
  );
  write(
    `docs/brand/vyrtel-lockup-tagline-${name}.svg`,
    svg(
      `${minX2} ${minY} ${maxX2 - minX2} ${maxY2 - minY}`,
      maxX2 - minX2,
      maxY2 - minY,
      `Vyrtel. ${TAGLINE}`,
      `${mark(MIDNIGHT, PAPER)}<path fill="${v.word}" d="${w.d}"/><path fill="${v.tag}" d="${tag.toPathData(2)}"/>`,
    ),
  );
}

// ---------- web UI path data ----------

// Font size 100 => 1 unit = 0.01em; baseline at y = 0; -0.04em tracking.
const ui = word(bold, 0, 0, 100, -4);
const asc = (bold.ascender / bold.unitsPerEm) * 100;
const desc = (-bold.descender / bold.unitsPerEm) * 100;
write(
  'web/src/lib/wordmark.ts',
  `/**
 * "yrtel" outlined from Inter Bold (kerned, -0.04em tracking) at font size 100: 1 unit = 0.01em,
 * baseline at y = 0, pen origin at x = 0. Drawn as a path rather than live text so it renders with
 * the same greyscale anti-aliasing as the Trace V (live text gets ClearType colour fringes on
 * Windows) and matches the outlined master in docs/brand/. Generated by docs/brand/generate.mjs.
 */
export const WORD = {
  width: ${+ui.end.toFixed(2)},
  ascender: ${+asc.toFixed(2)},
  descender: ${+desc.toFixed(2)},
  path: '${ui.d}',
} as const;
`,
);

console.log(`Wrote:\n  ${written.join('\n  ')}`);
